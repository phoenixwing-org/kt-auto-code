import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";

describe("Run Primary panel", () => {
  it("以 VS Code 风格 Tree 呈现目标，保持连续名称路径与执行/停止/版本动作", () => {
    const source = readFileSync(new URL("./KtcRunPrimaryPanel.ts", import.meta.url), "utf8");
    const entrySource = readFileSync(new URL("./KtcRunPrimaryPanelEntry.ts", import.meta.url), "utf8");
    const controllerSource = readFileSync(new URL("./KtcRunController.ts", import.meta.url), "utf8");
    const modelSource = readFileSync(new URL("../../core/run/KtcRunModel.ts", import.meta.url), "utf8");
    const manifest = JSON.parse(readFileSync(new URL("../../../package.json", import.meta.url), "utf8")) as {
      contributes: { configuration: { properties: Record<string, unknown> } };
    };
    expect(source).toContain('KtcRunPrimaryPanelTag = "ktc-run-primary-panel"');
    expect(modelSource).toContain('title: "CMake"');
    expect(modelSource).toContain('title: "Tasks"');
    expect(modelSource).toContain('title: "自定义"');
    expect(modelSource).toContain('title: "内置"');
    expect(source).toContain("KtcCompactManagerLabelStyle + KtcRunPrimaryPanelStyle");
    expect(source).toContain('className = "badge-tail"');
    expect(source).toContain('document.createElement("pnw-navigation-tree")');
    expect(source).toContain("overflow: visible !important; overscroll-behavior: auto !important");
    expect(source).toContain("把滚动交回 Primary 外层");
    expect(entrySource).toContain('import { pnwCodeDefineNavigationTree } from "@phoenix-wing/code-core/ui"');
    expect(entrySource).toContain("pnwCodeDefineNavigationTree()");
    expect(source).toContain('ariaLabel: "运行目标树"');
    expect(source).toContain("private readonly expandedNodeIds");
    expect(source).toContain("private readonly groupIdsByProjectNodeId");
    expect(source).toContain('"pnw-navigation-tree-action"');
    expect(source).toContain("this.handleTreeAction");
    expect(source).toContain("this.expandProjectWithGroups(projectId)");
    expect(source).toContain("select + 唯一 toggle");
    expect(source).toContain("展开状态只由上面的标准 toggle 事件回写");
    expect(source).not.toContain("expandableNodeIds");
    expect(source).not.toContain("isDuplicateRowToggle");
    expect(source).toContain("projectNode(project, index)");
    expect(source).toContain("targetNode(project, target)");
    expect(source).toContain("selectedNodeId: this.selectedNodeId");
    expect(source).toContain("单击即直接调用 Host runner");
    expect(source).toContain("this.runSelectedTarget();");
    expect(source).not.toContain('className = "selection-action primary"');
    expect(source).not.toContain("进入确认流程");
    expect(source).toContain('label: "运行辅助"');
    expect(source).toContain('"openTerminal"');
    expect(source).toContain('"openProblems"');
    expect(source).toContain('"openOutput"');
    expect(source).not.toContain('document.createElement("details")');
    expect(source).toContain('"ktc-run-primary-action"');
    expect(source).toContain('action: "runTarget"');
    expect(source).toContain('action: "dryRunTarget"');
    expect(source).toContain('action: "stopRun"');
    expect(source).toContain('action: "setCaaVersion"');
    expect(source).not.toContain('action: "setCaaRuntimeDirectory"');
    expect(source).not.toContain('document.createTextNode("编译平台")');
    expect(source).toContain('action: "selectCaaRelated"');
    expect(source).toContain('action: "addCaaRelatedFolder"');
    expect(source).toContain('target.availability === "other-platform"');
    expect(source).toContain('else if (target.availability === "other-platform")');
    expect(controllerSource).toContain('[Run][trial] execute=false');
    expect(controllerSource).toContain("KtcCaaBuildProblemMatchers(problemMatchers)");
    expect(controllerSource).toContain("为避免 RADE 输出和 Problems 诊断互相覆盖");
    expect(controllerSource).toContain('[Run][运行][INFO] ${record.target.label} · ${record.project.project.label} 已启动。');
    expect(controllerSource).toContain('[Run][CAA 预检][INFO] ${mode === "build" ? "内置 MK" : "内置 Run"}');
    expect(controllerSource).toContain('CAA：CATIA 未安装或目录不可访问');
    expect(controllerSource).toContain('[Run][运行][ERROR] ${identity} 失败');
    expect(controllerSource).toContain('KtcRequireCaaDirectory(installation.radeRoot, "RADE 根目录", ctx)');
    expect(controllerSource).toContain('KtcRequireCaaDirectory(installation.catiaRoot, "CATIA 目录", ctx)');
    expect(controllerSource).toContain('function KtcRunCompletionMessage');
    expect(controllerSource).not.toContain('运行“${record.target.label}”？');
    expect(controllerSource).not.toContain('"确认运行"');
    expect(controllerSource).toContain('[Run][trial] command=');
    expect(controllerSource).toContain('plannedPlatform=${plannedPlatform}');
    expect(controllerSource).toContain('function KtcRunLogArgument');
    expect(controllerSource).toContain('function KtcRunLogIdentity');
    expect(controllerSource).toContain('createBundledClangFormatLaunchPlan');
    expect(controllerSource).toContain("KtcCaaVersionSelectionStateKey");
    expect(controllerSource).toContain("workspaceState.update(KtcCaaVersionSelectionStateKey, values)");
    expect(controllerSource).toContain('update("caaRelatedProjects", values, vscode.ConfigurationTarget.WorkspaceFolder)');
    expect(controllerSource).toContain('update("caaProjects", projects, vscode.ConfigurationTarget.WorkspaceFolder)');
    expect(controllerSource).toContain("KtcSerializeCaaRelatedProjects");
    expect(controllerSource).toContain("KtcResolveCaaRelatedProjects");
    expect(manifest.contributes.configuration.properties).toHaveProperty("ktAutoCode.run.CAAVersion");
    expect(manifest.contributes.configuration.properties).toHaveProperty("ktAutoCode.run.CAARadeRoot");
    expect(manifest.contributes.configuration.properties).toHaveProperty("ktAutoCode.run.CATIARoot");
    expect(manifest.contributes.configuration.properties).not.toHaveProperty("ktAutoCode.run.caaRuntimeDirectory");
    expect(manifest.contributes.configuration.properties).toHaveProperty("ktAutoCode.run.caaRelatedProjects");
    expect(manifest.contributes.configuration.properties).toHaveProperty("ktAutoCode.run.caaProjects");
    expect(manifest.contributes.configuration.properties["ktAutoCode.run.CAAVersion"]).toMatchObject({ scope: "machine" });
    expect(manifest.contributes.configuration.properties["ktAutoCode.run.CAARadeRoot"]).toMatchObject({ scope: "machine" });
    expect(manifest.contributes.configuration.properties["ktAutoCode.run.CATIARoot"]).toMatchObject({ scope: "machine" });
    expect(controllerSource).toContain('configuration.inspect<string>("caaVersion")');
    expect(controllerSource).toContain('configuration.get<string>("caaRadeRoot")');
    expect(controllerSource).toContain('configuration.get<string>("caaCatiaRoot")');
    expect(source).not.toContain("acquireVsCodeApi");
  });
});
